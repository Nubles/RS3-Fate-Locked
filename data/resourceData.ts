// RuneScape 3 Resource Engine catalogue.
//
// Every obtainable item the Resource Engine (components/SupplyChainCalculator)
// knows about, keyed by its Title Case display name, with every way to get it:
// gathering skill + level, monster drops, shops, minigames/bosses (unlockId →
// an entry in one of the unlock lists in data/items.ts) and crafting recipes
// (`inputs`). Regions are RS3 continents / sub-regions from REGION_GROUPS, or
// MISTHALIN_AREAS / 'Misthalin', or 'Any'.
//
// Items are declared per browsing category with `section()`, which fills both
// RESOURCE_MAP and RESOURCE_CATEGORIES so the two can never drift. Families
// with a regular shape (metal tiers, herbs, fish, jewellery) are generated by
// small helpers from verified RS3 tables (runescape.wiki, 2026) — see
// docs/RESOURCE_ENGINE.md for the sources and the maintenance workflow.
import { ENRICHED_SOURCES } from './resourceEnrichment';

export type SourceType =
  | 'DROP'
  | 'SHOP'
  | 'SPAWN'
  | 'SKILL'
  | 'MINIGAME'
  | 'MERCHANT'
  | 'QUEST'
  | 'PICKPOCKET' // Thieving NPCs / stalls
  | 'CLUE';      // Treasure Trail rewards

export interface ResourceSource {
  type: SourceType;
  name: string; // e.g. "Chaos druid", "Herb Patch", "General Store"
  regions: string[]; // List of regions where this specific source exists
  skills?: Record<string, number>; // Specific levels required to access/kill
  quests?: string[];
  unlockId?: string; // Unlock-list entry gating this source (boss, minigame, guild, farming patch, …)
  notes?: string; // e.g. "Edgeville Dungeon"
  inputs?: Record<string, number>; // Ingredients -> Quantity
  outputYield?: number; // How many items are produced per operation (default 1)
  rarity?: string; // Drop rate / acquisition odds, e.g. "1/512", "Common", "Always"
}

export const RESOURCE_MAP: Record<string, ResourceSource[]> = {};
export const RESOURCE_CATEGORIES: Record<string, string[]> = {};

/** Register a browsing category and its items in both indexes. */
const section = (category: string, items: Record<string, ResourceSource[]>) => {
  const list = RESOURCE_CATEGORIES[category] ?? (RESOURCE_CATEGORIES[category] = []);
  for (const [item, sources] of Object.entries(items)) {
    list.push(item);
    RESOURCE_MAP[item] = sources;
  }
};

